package gov.uddp.core.studio;

import gov.uddp.core.studio.StudioModels.Crosswalk;
import gov.uddp.core.studio.StudioModels.CrosswalkEntry;
import gov.uddp.core.studio.StudioModels.Draft;
import gov.uddp.core.studio.StudioModels.GeneratedFile;
import gov.uddp.core.studio.StudioModels.MappingRule;
import gov.uddp.core.studio.StudioModels.Rules;
import gov.uddp.core.studio.StudioModels.Source;
import gov.uddp.core.studio.StudioModels.ValidationRule;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;
import org.springframework.stereotype.Component;

/**
 * Turns a draft into State Pack YAML in the existing spec format ({@code docs/state-pack-spec.md}), using the same
 * flow-style layout as the hand-written reference packs. Generic: the files depend only on the draft's content.
 */
@Component
public class PackGenerator {
    public static final String FILE_TEMPLATE = "generic-file-ingest.hpl";
    public static final String DATABASE_TEMPLATE = "generic-db-ingest.hpl";
    public static final String EXCEL_TEMPLATE = "generic-excel-ingest.hpl";
    static final String COMMON_MODEL_VERSION = "1.0.0";
    private static final List<String> ENTITY_ORDER = List.of("Resident", "Family", "Benefit");
    private static final Pattern PLAIN = Pattern.compile("[A-Za-z][A-Za-z0-9_./-]*");
    private static final Set<String> RESERVED = Set.of("true", "false", "yes", "no", "on", "off", "null", "y", "n", "~");

    /** The pack's files by relative path, in the order a reader expects them. */
    public List<GeneratedFile> generate(Draft draft, String version, Path repositoryRoot) {
        Source source = draft.source();
        if (source == null) {
            throw new IllegalArgumentException("Upload a source file (or choose a database table) first");
        }
        String sourceFile = "sources/" + source.sourceId() + ".yaml";
        String mappingFile = "mappings/" + source.sourceId() + "-resident.yaml";
        List<Crosswalk> crosswalks = usedCrosswalks(draft);
        List<GeneratedFile> files = new ArrayList<>();

        List<String> crosswalkFiles = crosswalks.stream().map(c -> "crosswalks/" + c.id() + ".yaml").toList();
        files.add(new GeneratedFile("state.yaml", String.join("\n",
                "# " + draft.displayName() + " - generated by the UDDP Onboarding Studio; do not edit by hand.",
                "packId: " + scalar(draft.packId()),
                "stateCode: " + scalar(draft.stateCode()),
                "version: " + version,
                "commonModelVersion: " + COMMON_MODEL_VERSION,
                "status: published",
                "sources: [" + sourceFile + "]",
                "mappings: [" + mappingFile + "]",
                "crosswalks: [" + String.join(", ", crosswalkFiles) + "]",
                "validation: [validation/resident.yaml]",
                "matching: [matching/resident.yaml]",
                "survivorship: [survivorship/resident.yaml]",
                "")));
        files.add(new GeneratedFile(sourceFile, source(source, repositoryRoot)));
        files.add(new GeneratedFile(mappingFile, mapping(draft)));
        for (Crosswalk crosswalk : crosswalks) {
            files.add(new GeneratedFile("crosswalks/" + crosswalk.id() + ".yaml", crosswalk(crosswalk)));
        }
        Rules rules = draft.rules();
        files.add(new GeneratedFile("validation/resident.yaml", validation(rules.validation())));
        files.add(new GeneratedFile("matching/resident.yaml", String.join("\n",
                "entity: Resident",
                "fields: " + list(rules.matching().fields()),
                "thresholds: { autoMatch: " + rules.matching().autoMatch() + ", possibleMatch: "
                        + rules.matching().possibleMatch() + " }",
                "")));
        files.add(new GeneratedFile("survivorship/resident.yaml", String.join("\n",
                "entity: Resident",
                "fieldPriority: " + priority(rules.survivorship()),
                "")));
        return files;
    }

    private static String source(Source source, Path repositoryRoot) {
        List<String> lines = new ArrayList<>();
        lines.add("sourceId: " + scalar(source.sourceId()));
        lines.add("sourceType: " + scalar(source.sourceType()));
        boolean database = "database".equals(source.sourceType());
        boolean workbook = !database && source.fileName() != null && source.fileName().toLowerCase(Locale.ROOT).endsWith(".xlsx");
        lines.add("hopTemplate: " + (database ? DATABASE_TEMPLATE : workbook ? EXCEL_TEMPLATE : FILE_TEMPLATE));
        if (workbook) {
            lines.add("format: xlsx");
        }
        if (database) {
            // A logical connection name only: credentials stay in the encrypted local settings store.
            lines.add("connectionRef: " + scalar(source.connectionName()));
            if (source.query() != null && !source.query().isBlank()) {
                lines.add("query: " + scalar(source.query()));
            } else {
                lines.add("table: " + scalar(source.table()));
            }
            if (source.changeColumn() != null && !source.changeColumn().isBlank()) {
                // Delta loads: each delivery reads only the rows past the last loaded change value.
                lines.add("changeColumn: " + scalar(source.changeColumn()));
            }
        } else {
            lines.add("connectionRef: studio-landing");
            lines.add("location: " + scalar(location(source.location(), repositoryRoot)));
        }
        if (workbook && source.sheets() != null && !source.sheets().isEmpty()) {
            lines.add("sheets: { " + String.join(", ", source.sheets().stream().map(name -> scalar(name) + ": {}").toList()) + " }");
        }
        lines.add("recordIdField: " + scalar(source.recordIdField()));
        if (source.recordKeyFields() != null && !source.recordKeyFields().isEmpty()) {
            lines.add("recordKeyFields: " + list(source.recordKeyFields()));
        }
        lines.add("sourceSchemaVersion: '1.0'");
        // The accepted Shape steps: without them a published workbook source would be read with no header and no
        // parsers, so nothing the Studio previewed would be mapped.
        if (!database) {
            lines.addAll(shapingLines(source.layout(), source.parse()));
        }
        lines.add("");
        return String.join("\n", lines);
    }

    /** The {@code layout:} and {@code parse:} sections of a source, one flow-style step per line; empty without steps. */
    public static List<String> shapingLines(List<Map<String, Object>> layout, List<Map<String, Object>> parse) {
        List<String> lines = new ArrayList<>();
        if (layout != null && !layout.isEmpty()) {
            lines.add("layout:");
            layout.forEach(step -> lines.add("  - " + flow(step)));
        }
        if (parse != null && !parse.isEmpty()) {
            lines.add("parse:");
            parse.forEach(step -> lines.add("  - " + flow(step)));
        }
        return lines;
    }

    /** A map, list or scalar in YAML flow style, e.g. {@code { op: ditto@1.0, columns: [A, B] }}. */
    static String flow(Object value) {
        if (value instanceof Map<?, ?> map) {
            if (map.isEmpty()) {
                return "{}";
            }
            return "{ " + String.join(", ", map.entrySet().stream()
                    .map(e -> scalar(String.valueOf(e.getKey())) + ": " + flow(e.getValue())).toList()) + " }";
        }
        if (value instanceof Iterable<?> list) {
            List<String> items = new ArrayList<>();
            list.forEach(item -> items.add(flow(item)));
            return "[" + String.join(", ", items) + "]";
        }
        if (value instanceof Number || value instanceof Boolean) {
            return String.valueOf(value);
        }
        return scalar(value == null ? null : String.valueOf(value));
    }

    /** A landed file inside the repository is referenced relative to its root, like the reference packs. */
    static String location(String location, Path repositoryRoot) {
        Path file = Path.of(location).toAbsolutePath().normalize();
        Path root = repositoryRoot.toAbsolutePath().normalize();
        return file.startsWith(root) ? root.relativize(file).toString().replace('\\', '/') : file.toString();
    }

    private static String mapping(Draft draft) {
        List<String> lines = new ArrayList<>();
        lines.add("mappingVersion: 1.0.0");
        lines.add("sourceId: " + scalar(draft.source().sourceId()));
        lines.add("entities:");
        Map<String, List<MappingRule>> byEntity = new LinkedHashMap<>();
        ENTITY_ORDER.forEach(entity -> byEntity.put(entity, new ArrayList<>()));
        for (MappingRule rule : draft.mappings()) {
            byEntity.computeIfAbsent(rule.entity(), k -> new ArrayList<>()).add(rule);
        }
        byEntity.forEach((entity, rules) -> {
            if (rules.isEmpty()) {
                return;
            }
            lines.add("  " + entity + ":");
            for (MappingRule rule : rules) {
                StringBuilder line = new StringBuilder("    - { sourceField: ").append(scalar(rule.sourceField()))
                        .append(", target: ").append(scalar(rule.target()));
                if (rule.conversion() != null && !rule.conversion().isBlank()) {
                    line.append(", conversion: ").append(scalar(rule.conversion()));
                }
                if (rule.crosswalk() != null && !rule.crosswalk().isBlank()) {
                    line.append(", crosswalk: ").append(scalar(rule.crosswalk()));
                }
                if (Boolean.TRUE.equals(rule.required())) {
                    line.append(", required: true");
                }
                lines.add(line.append(" }").toString());
            }
        });
        lines.add("");
        return String.join("\n", lines);
    }

    private static String crosswalk(Crosswalk crosswalk) {
        List<String> pairs = new ArrayList<>();
        for (CrosswalkEntry entry : crosswalk.entries()) {
            if (entry.targetValue() != null && !entry.targetValue().isBlank()) {
                pairs.add(scalar(entry.sourceValue()) + ": " + scalar(entry.targetValue()));
            }
        }
        return "id: " + scalar(crosswalk.id()) + "\nvalues: { " + String.join(", ", pairs) + " }\n";
    }

    private static String validation(List<ValidationRule> rules) {
        List<String> lines = new ArrayList<>();
        lines.add("entity: Resident");
        lines.add("rules:");
        for (ValidationRule rule : rules) {
            List<String> parts = new ArrayList<>();
            if (rule.id() != null && !rule.id().isBlank()) {
                parts.add("id: " + scalar(rule.id()));
            }
            if (rule.type() != null && !rule.type().isBlank()) {
                parts.add("type: " + scalar(rule.type()));
            }
            parts.add("field: " + scalar(rule.field()));
            if (rule.required() != null) {
                parts.add("required: " + rule.required());
            }
            if (rule.allowedValues() != null && !rule.allowedValues().isEmpty()) {
                parts.add("allowedValues: " + list(rule.allowedValues()));
            }
            if (rule.pattern() != null && !rule.pattern().isBlank()) {
                parts.add("pattern: " + quoted(rule.pattern()));
            }
            if (rule.referenceSet() != null && !rule.referenceSet().isBlank()) {
                parts.add("referenceSet: " + scalar(rule.referenceSet()));
            }
            parts.add("severity: " + scalar(rule.severity().toLowerCase(Locale.ROOT)));
            lines.add("  - { " + String.join(", ", parts) + " }");
        }
        if (rules.isEmpty()) {
            lines.set(1, "rules: []");
        }
        lines.add("");
        return String.join("\n", lines);
    }

    private static String priority(Map<String, List<String>> fieldPriority) {
        if (fieldPriority == null || fieldPriority.isEmpty()) {
            return "{}";
        }
        List<String> parts = new ArrayList<>();
        fieldPriority.forEach((field, sources) -> parts.add(scalar(field) + ": " + list(sources)));
        return "{ " + String.join(", ", parts) + " }";
    }

    /** Crosswalks referenced by at least one mapping rule, in rule order. */
    private static List<Crosswalk> usedCrosswalks(Draft draft) {
        Map<String, Crosswalk> byId = new LinkedHashMap<>();
        draft.crosswalks().forEach(c -> byId.put(c.id(), c));
        List<Crosswalk> used = new ArrayList<>();
        for (MappingRule rule : draft.mappings()) {
            Crosswalk crosswalk = rule.crosswalk() == null ? null : byId.get(rule.crosswalk());
            if (crosswalk != null && !used.contains(crosswalk)) {
                used.add(crosswalk);
            }
        }
        return used;
    }

    static String list(List<String> values) {
        return "[" + String.join(", ", values.stream().map(PackGenerator::scalar).toList()) + "]";
    }

    /** A YAML scalar: plain when unambiguous, otherwise single-quoted. */
    static String scalar(String value) {
        if (value == null) {
            return "''";
        }
        if (PLAIN.matcher(value).matches() && !RESERVED.contains(value.toLowerCase(Locale.ROOT))) {
            return value;
        }
        return quoted(value);
    }

    private static String quoted(String value) {
        return "'" + value.replace("'", "''") + "'";
    }
}
